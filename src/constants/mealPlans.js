export const findMealPlan = (planId) => MEAL_PLANS.find((plan) => plan.id === planId) || null;

// Дэглэмийг одоогийн meals объект руу хөрвүүлнэ. Дэглэмд байхгүй өдөр
// (хэзээ ч тохиолдохгүй ч) хуучин утгаа хадгална — өгөгдөл алдагдахгүй.
export const applyMealPlan = (planId, currentMeals = {}) => {
  const plan = findMealPlan(planId);
  if (!plan) return currentMeals;
  const next = { ...currentMeals };
  Object.keys(plan.days).forEach((dayKey) => {
    next[dayKey] = { ...plan.days[dayKey] };
  });
  return next;
};
